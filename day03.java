public class day03 {
    public static void main(String[] args) {
	
        // \n (New Line)
        System.out.println("First line.\nSecond line.");
        
        // \t (Tab)
        System.out.println("Nama\t:\tRhaifan Firansyah");
        System.out.println("NIM\t:\tD0226040");
        System.out.println("Prodi\t:\tInformatika");
        
        // \" (Double Quotation Marks)
        System.out.println("Suka berkata \"Bagus!\"");
        
        // \\ (Backslash)
        System.out.println("Alamat File : \\Dokumen\\100DaysofCoding");
        
    }
}
